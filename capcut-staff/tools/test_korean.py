"""한국어 끊어읽기 판단 회귀 테스트.

    python tools/test_korean.py

끊는 자리 규칙은 손대다 보면 한쪽을 고치고 다른 쪽을 깨기 쉽다.
("바로" 를 부사로 잡으려다 "촬영본을" 뒤를 막아버린 적이 있다)
여기 사례를 박아두고 매번 돌린다.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from capcut_agent.korean import break_score, chunk  # noqa: E402

# 붙어 있어야 하는 자리 (점수가 음수여야 한다)
MUST_JOIN = [
    ("자동", "편집에", "합성어 '자동 편집'"),
    ("만든", "자동", "관형형 + 체언"),
    ("하는", "실수가", "관형형 + 체언"),
    ("이", "사람이", "관형사 + 체언"),
    ("그", "부분은", "관형사 + 체언"),
    ("말한", "것을", "의존명사 '것'"),
    ("가르칠", "때", "의존명사 '때'"),
    ("할", "수", "의존명사 '수'"),
    ("정리해", "볼", "보조용언 '보다'"),
    ("편집해", "줍니다.", "보조용언 '주다'"),
    ("먹고", "있습니다", "보조용언 '있다'"),
    ("바로", "초벌", "부사"),
    ("가장", "많이", "부사"),
    ("확실히", "좋은", "부사 '~히'"),
    ("많이", "하는", "부사"),
    ("편집에", "대해", "후치사 '~에 대해'"),
    ("성공을", "위해", "후치사 '~을 위해'"),
    ("그것", "때문에", "후치사 '~ 때문에'"),
    ("회사의", "대표는", "관형격 '의'"),
    # 2026-09-16 대표님 지적 — 0916 영상
    ("있는", "걸", "줄어든 의존명사 '걸'(=것을)"),
    ("잘", "보여줄", "정도 부사 '잘' 뒤"),
    ("수", "있는", "'~ㄹ 수 있다' 의 수 뒤"),
]

# 끊어도 되는 자리 (점수가 양수여야 한다)
MUST_BREAK = [
    ("있습니다.", "그런데", "문장 끝"),
    ("합니다.", "안녕하세요", "문장 끝"),
    ("오늘은", "영상", "주제격 조사"),
    ("촬영본을", "바로", "목적격 조사"),
    ("도구는", "촬영본을", "주제격 조사"),
    ("내용은", "세", "주제격 조사"),
    ("대해", "이야기하겠습니다.", "후치사구 끝"),
    ("만들고", "그다음에", "연결어미"),
    ("좋은데", "문제가", "연결어미"),
    ("있습니다", "그리고", "접속부사 앞"),
    # 2026-09-16 대표님 지적 — 0916 영상
    ("트레이너는", "잘", "'잘' 앞은 끊어도 된다"),
    ("걸", "많은", "'걸' 뒤는 끊어도 된다"),
]

# 오탐 점검 — 의존명사/보조용언 사전이 **뒷 낱말의 앞글자**에 걸리면 안 된다.
# 앞 낱말은 확실히 끊어도 되는 것(문장 끝, 조사)으로 고정해서 규칙을 격리한다.
NO_FALSE_POSITIVE = [
    ("있습니다.", "지금", "'지'(의존명사) 오탐"),
    ("내용은", "데이터를", "'데' 오탐"),
    ("있습니다.", "중요한", "'중' 오탐"),
    ("합니다.", "안녕하세요", "'안' 오탐"),
    ("내용은", "번역이", "'번' 오탐"),
    ("있습니다.", "수업이", "'수' 오탐"),
    ("내용은", "오늘은", "보조용언 '오' 오탐"),
    ("있습니다.", "가격이", "보조용언 '가' 오탐"),
    ("내용은", "바로", "'바'(의존명사) 오탐"),
    ("있습니다.", "대표는", "'대' 오탐"),
    # 체언+조사 축약형 뒤에서도 끊을 수 있어야 한다
    ("이건", "지금", "축약형 '이건'"),
    ("이게", "제일", "축약형 '이게'"),
]

# 문장 → 줄 나누기 기대값 (전부 max_chars 이하 + 지정 어구가 안 갈라져야 함)
CHUNK_CASES = [
    ("안녕하세요. 오늘은 영상 자동 편집에 대해 이야기하겠습니다.", 18,
     ["자동 편집에", "대해"]),
    ("트레이너분들이 가장 많이 하는 실수가 바로 이 부분입니다.", 18,
     ["가장 많이", "하는 실수가", "바로 이 부분입니다."]),
    ("그러니까 이 사람이 말한 것을 다시 한번 정리해 볼 필요가 있습니다.", 18,
     ["이 사람이", "말한 것을", "정리해 볼"]),
    ("회원님한테 운동을 가르칠 때 제일 중요한 게 뭐냐면 자세입니다.", 18,
     ["가르칠 때"]),
    # 2026-09-16 대표님 지적 — 0916 영상에서 실제로 틀렸던 두 문장
    ("수업을 못하는 트레이너는 잘 보여줄 수도 없습니다", 23,
     ["잘 보여줄"]),
    ("결국 수업을 잘하고 수업 잘하고 있는 걸 많은 사람들이 알게끔 하는", 23,
     ["있는 걸"]),
]

fails: list[str] = []


def main() -> int:
    print("── 붙어야 하는 자리 ──")
    for a, b, why in MUST_JOIN:
        s = break_score(a, b)
        ok = s < 0
        print(f"  {'OK ' if ok else '실패'}  {a} │ {b:<12} {s:>5}   {why}")
        if not ok:
            fails.append(f"붙어야 함: {a} | {b} (점수 {s}) — {why}")

    print("\n── 끊어도 되는 자리 ──")
    for a, b, why in MUST_BREAK + NO_FALSE_POSITIVE:
        s = break_score(a, b)
        ok = s > 0
        print(f"  {'OK ' if ok else '실패'}  {a} │ {b:<12} {s:>5}   {why}")
        if not ok:
            fails.append(f"끊어도 됨: {a} | {b} (점수 {s}) — {why}")

    print("\n── 줄 나누기 ──")
    for text, mx, keep_together in CHUNK_CASES:
        ws = text.split()
        lines = [" ".join(ws[i] for i in g) for g in chunk(ws, mx)]
        print(f"  {text}")
        for ln in lines:
            over = "  ← 초과!" if len(ln) > mx else ""
            print(f"     │ {ln}  ({len(ln)}자){over}")
            if len(ln) > mx:
                fails.append(f"길이 초과: {ln!r} ({len(ln)}자 > {mx})")
        for phrase in keep_together:
            if not any(phrase in ln for ln in lines):
                fails.append(f"어구가 갈라짐: {phrase!r} in {text!r}")
                print(f"     ✕ '{phrase}' 가 갈라짐")
        print()

    if fails:
        print(f"실패 {len(fails)}건")
        for f in fails:
            print(f"  · {f}")
        return 1
    print(f"전부 통과 ({len(MUST_JOIN) + len(MUST_BREAK) + len(NO_FALSE_POSITIVE)}개 "
          f"자리 + {len(CHUNK_CASES)}개 문장)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
